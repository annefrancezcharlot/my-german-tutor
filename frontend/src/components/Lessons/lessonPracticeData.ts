export interface SentenceDrill {
  id: string;
  topic: string;
  /** Use ___ for the blank */
  text: string;
  case: 'N' | 'A' | 'D' | 'G';
  answers: string[];
  hint: string;
}

const s = (topic: string, hint: string, items: [string, SentenceDrill['case'], string | string[]][]): SentenceDrill[] =>
  items.map(([text, c, answers], i) => ({
    id: `${topic}-${i}`, topic, text, case: c, hint, answers: Array.isArray(answers) ? answers : [answers],
  }));

